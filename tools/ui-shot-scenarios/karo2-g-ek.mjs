// Karo galerisi ek: Patch notes, jenerik, kahraman seçici başlığı, Form your company, Gear başlık süsü, sandık. KARO_OUT=<klasör>.
import { dbg, startCampaign, tutorialsOff, scene } from './_lib.mjs';
import { HIDE_DEBUG, autoRing, autoRingPhaser, hookPhaser, titleOrn, ring, ctxShot, saveManifest } from './karo2-lib.mjs';
const full = (page, n) => ctxShot(page, { x: 5, y: 5, s: 1 }, n);
export default async ({ page, wait, view }) => {
  await page.addStyleTag({ content: HIDE_DEBUG });
  await hookPhaser(page);
  await tutorialsOff(page);
  await page.evaluate(async () => { (await import('/src/ui/patch-notes.ts')).openPatchNotes(); });
  await wait(1800);
  await autoRing(page, 'ek-patch');
  await full(page, 'ek-patch-tam');
  await page.keyboard.press('Escape');
  await wait(900);
  await page.evaluate(() => document.querySelectorAll('.pn-wrap, .patch-notes, [class*="pn-"]').forEach((e) => e.closest('[class*="overlay"], .pn-wrap')?.remove()));
  await page.evaluate(async () => { const m = await import('/src/ui/credits.ts'); window.__cr = m.openCredits(document.getElementById('ui-root') ?? document.body); });
  await wait(2500);
  await autoRing(page, 'ek-jenerik');
  await full(page, 'ek-jenerik-tam');
  await page.evaluate(() => window.__cr?.close?.());
  await wait(800);
  await startCampaign(page, wait, { idx: 0, onPicker: async (p) => { await ring(p, await titleOrn(p, '.mw.hp .mw-hd h2, .mw.hp .mw-hd .mw-t, .mw.hp .mw-title'), 'ek-secici-baslik'); await full(p, 'ek-secici-tam'); } });
  await page.addStyleTag({ content: HIDE_DEBUG });
  await wait(1200);
  await scene(page, 'CampaignMapScene', (sc) => sc.companyModal(4));
  await wait(2000);
  await autoRing(page, 'ek-sirket');
  await full(page, 'ek-sirket-tam');
  await page.evaluate(() => document.querySelectorAll('.cw').forEach((e) => e.remove()));
  await page.keyboard.press('Escape');
  await wait(800);
  await dbg(page, 'campaign.gear');
  await wait(3000);
  await ring(page, await titleOrn(page, '.gr-head > .gr-title'), 'ek-gear-baslik');
  await page.keyboard.press('Escape');
  await wait(1000);
  await dbg(page, 'campaign.chest');
  await wait(5000);
  await autoRing(page, 'ek-sandik');
  await autoRingPhaser(page, 'ek-sandik', { limit: 4 });
  await full(page, 'ek-sandik-tam');
  await saveManifest(view);
};
